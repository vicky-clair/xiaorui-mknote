    public static string CurrentLanguage { get; set; } = "zh-CN";

    public static string T(string key, string? lang = null)
    {
        var l = lang ?? CurrentLanguage;
        if (Dict.TryGetValue(l, out var table) && table.TryGetValue(key, out var val))
            return val;
        if (Dict["zh-CN"].TryGetValue(key, out var fallback))
            return fallback;
        return key;
    }

